pub struct Epd {
    spi: SpiDeviceDriver<'static, SpiDriver<'static>>,
    dc: PinDriver<'static, Output>,
    rst: PinDriver<'static, Output>,
    busy: PinDriver<'static, Input>,
    partial_mode: bool,
}

impl Epd {
    pub fn new(
        spi: SpiDeviceDriver<'static, SpiDriver<'static>>,
        dc: PinDriver<'static, Output>,
        rst: PinDriver<'static, Output>,
        busy: PinDriver<'static, Input>,
    ) -> Self {
        Self { spi, dc, rst, busy, partial_mode: false }
    }

    fn cmd(&mut self, c: u8) {
        let _ = self.dc.set_low();
        let _ = self.spi.write(&[c]);
    }

    fn data(&mut self, d: &[u8]) {
        let _ = self.dc.set_high();
        for chunk in d.chunks(2048) {
            let _ = self.spi.write(chunk);
        }
    }

    fn wait(&mut self) {
        let start = Instant::now();
        while self.busy.is_high() {
            if start.elapsed() > Duration::from_secs(10) {
                log::warn!("epd: busy timeout");
                break;
            }
            FreeRtos::delay_ms(5);
        }
    }

    fn reset(&mut self) {
        let _ = self.rst.set_high();
        FreeRtos::delay_ms(20);
        let _ = self.rst.set_low();
        FreeRtos::delay_ms(5);
        let _ = self.rst.set_high();
        FreeRtos::delay_ms(20);
        self.wait();
    }

    fn set_lut(&mut self, lut: &[u8; 159]) {
        self.cmd(0x32);
        self.data(&lut[..153]);
        self.wait();
        self.cmd(0x3F);
        self.data(&[lut[153]]);
        self.cmd(0x03);
        self.data(&[lut[154]]);
        self.cmd(0x04);
        self.data(&[lut[155], lut[156], lut[157]]);
        self.cmd(0x2C);
        self.data(&[lut[158]]);
    }

    /// Orientation and RAM window (same in full and partial mode).
    fn setup_ram(&mut self) {
        self.cmd(0x01); // driver output control
        self.data(&[0xC7, 0x00, 0x01]);
        self.cmd(0x11); // data entry: X+, Y−
        self.data(&[0x01]);
        self.cmd(0x44);
        self.data(&[0x00, 199 / 8]);
        self.cmd(0x45);
        self.data(&[199, 0, 0, 0]);
    }

    fn cursor(&mut self) {
        self.cmd(0x4E);
        self.data(&[0x00]);
        self.cmd(0x4F);
        self.data(&[199, 0]);
    }

    fn init_full(&mut self) {
        self.reset();
        self.cmd(0x12); // SW reset
        self.wait();
        self.setup_ram();
        self.cmd(0x3C); // border
        self.data(&[0x01]);
        self.cmd(0x18); // internal temperature sensor
        self.data(&[0x80]);
        self.cmd(0x22);
        self.data(&[0xB1]);
        self.cmd(0x20);
        self.wait();
        self.cursor();
        self.set_lut(&LUT_FULL);
        self.partial_mode = false;
    }

    fn enter_partial(&mut self) {
        self.set_lut(&LUT_PARTIAL);
        self.cmd(0x37);
        self.data(&[0x00, 0x00, 0x00, 0x00, 0x00, 0x40, 0x00, 0x00, 0x00, 0x00]);
        self.cmd(0x3C);
        self.data(&[0x80]);
        self.cmd(0x22);
        self.data(&[0xC0]);
        self.cmd(0x20);
        self.wait();
        self.partial_mode = true;
    }

    /// Full refresh (flashes, clears ghosting). Leaves the panel ready for partial updates.
    pub fn full(&mut self, f: &Frame) {
        self.init_full();
        self.cursor();
        self.cmd(0x24);
        self.data(&f.buf[..BYTES]);
        self.cursor();
        self.cmd(0x26);
        self.data(&f.buf[..BYTES]);
        self.cmd(0x22);
        self.data(&[0xC7]);
        self.cmd(0x20);
        self.wait();
        self.enter_partial();
    }

    /// Fast update without flashing.
    pub fn partial(&mut self, f: &Frame) {
        if !self.partial_mode {
            return self.full(f);
        }
        self.cursor();
        self.cmd(0x24);
        self.data(&f.buf[..BYTES]);
        self.cmd(0x22);
        self.data(&[0xCF]);
        self.cmd(0x20);
        self.wait();
    }

    /// Deep sleep (panel keeps the image). Next update does a full refresh.
    pub fn sleep(&mut self) {
        self.cmd(0x10);
        self.data(&[0x01]);
        self.partial_mode = false;
    }
}
