use anyhow::{bail, Context, Result};
use serde::Deserialize;
use std::fmt::Write;

#[derive(Deserialize)]
struct File {
    default: String,
    city: Vec<City>,
}

#[derive(Deserialize)]
struct City {
    key: String,
    name: String,
    tz: String,
    diyanet_id: u32,
}

/// The POSIX TZ footer of a TZif v2+ file is the last newline-delimited line.
fn posix_tz(zone: &str) -> Result<String> {
    let data = std::fs::read(format!("/usr/share/zoneinfo/{zone}"))
        .with_context(|| format!("zoneinfo for {zone}"))?;
    let trimmed = data.strip_suffix(b"\n").context("no TZ footer")?;
    let start = trimmed.iter().rposition(|&b| b == b'\n').context("no TZ footer")? + 1;
    let s = std::str::from_utf8(&trimmed[start..])?.to_string();
    if s.is_empty() {
        bail!("empty TZ footer for {zone}");
    }
    Ok(s)
}

/// Standard offset from a POSIX TZ string ("<+03>-3", "IST-5:30", "EST5EDT,…").
/// POSIX offsets are west-positive, so the sign is flipped.
fn utc_label(posix: &str) -> Result<String> {
    let rest = if let Some(r) = posix.strip_prefix('<') {
        &r[r.find('>').context("bad <name>")? + 1..]
    } else {
        posix.trim_start_matches(|c: char| c.is_ascii_alphabetic())
    };
    let end = rest
        .find(|c: char| !(c.is_ascii_digit() || c == ':' || c == '+' || c == '-'))
        .unwrap_or(rest.len());
    let off = &rest[..end];
    let (neg, num) = match off.as_bytes().first() {
        Some(b'-') => (false, &off[1..]),
        Some(b'+') => (true, &off[1..]),
        _ => (true, off),
    };
    let mut parts = num.split(':');
    let h: u32 = parts.next().context("offset")?.parse()?;
    let m: u32 = parts.next().map(|m| m.parse()).transpose()?.unwrap_or(0);
    let sign = if h == 0 && m == 0 || !neg { "+" } else { "-" };
    Ok(if m == 0 { format!("UTC{sign}{h}") } else { format!("UTC{sign}{h}:{m:02}") })
}

pub fn generate() -> Result<()> {
    let root = crate::root();
    let f: File = toml::from_str(&std::fs::read_to_string(root.join("cities.toml"))?)?;
    let default = f.city.iter().position(|c| c.key == f.default).context("default city not in list")?;
    let mut out = String::from(
        "// @generated by `cargo xtask cities` from cities.toml. Do not edit.\n\npub static CITIES: &[City] = &[\n",
    );
    for c in &f.city {
        let posix = posix_tz(&c.tz)?;
        let label = utc_label(&posix)?;
        writeln!(
            out,
            "    City {{ key: {:?}, name: {:?}, tz_iana: {:?}, tz_posix: {:?}, diyanet_id: {}, utc_label: {:?} }},",
            c.key, c.name, c.tz, posix, c.diyanet_id, label
        )?;
        println!("{:<14} {:<10} {:<38} {}", c.name, label, posix, c.diyanet_id);
    }
    writeln!(out, "];\n\npub const DEFAULT_CITY: usize = {default};")?;
    std::fs::write(root.join("core/src/cities_gen.rs"), out)?;
    println!("wrote core/src/cities_gen.rs ({} cities)", f.city.len());
    Ok(())
}

#[cfg(test)]
mod tests {
    #[test]
    fn labels() {
        assert_eq!(super::utc_label("<+03>-3").unwrap(), "UTC+3");
        assert_eq!(super::utc_label("IST-5:30").unwrap(), "UTC+5:30");
        assert_eq!(super::utc_label("EST5EDT,M3.2.0,M11.1.0").unwrap(), "UTC-5");
        assert_eq!(super::utc_label("GMT0BST,M3.5.0/1,M10.5.0").unwrap(), "UTC+0");
    }
}
